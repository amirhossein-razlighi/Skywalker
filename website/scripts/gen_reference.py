def load(name: str):
    return json.loads((DATA / name).read_text())


def md_escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").replace("<", "&lt;").replace(">", "&gt;")


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9_-]+", "-", text.lower()).strip("-")


def balanced_json(text: str, start: int) -> str | None:
    depth, i, in_str = 0, start, False
    while i < len(text):
        c = text[i]
        if in_str:
            if c == "\\":
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return text[start:i + 1]
        i += 1
    return None


def described_example(desc: str):
    for m in re.finditer(r"(?i)\bexamples?\b[^{]{0,30}?(\{)", desc):
        raw = balanced_json(desc, m.start(1))
        if raw:
            try:
                value = json.loads(raw)
            except json.JSONDecodeError:
                continue
            if isinstance(value, dict):
                return value
    return None


def sample_value(name: str, schema: dict):
    if "enum" in schema and schema["enum"]:
        return schema["enum"][0]
    t = schema.get("type")
    if isinstance(t, list):
        t = t[0]
    if t == "string" or t is None:
        v = SAMPLE_STRINGS.get(name)
        return v if v is not None else name.replace("_", " ")
    if t == "integer":
        return int(max(schema.get("minimum", 1), 1))
    if t == "number":
        return max(schema.get("minimum", 1), 1)
    if t == "boolean":
        return True
    if t == "array":
        items = schema.get("items", {})
        return [sample_value(name.rstrip("s"), items if isinstance(items, dict) else {})]
    if t == "object":
        return {}
    return name


_MINED: dict | None = None


def mined_examples(tools: dict[str, dict]) -> dict[str, dict]:
    """Example calls written by the engine's authors in docs/*.md and the skills (validated against the schema)."""
    global _MINED
    if _MINED is not None:
        return _MINED
    import importlib.util
    spec = importlib.util.spec_from_file_location("check_skills", ROOT / "integrations" / "check_skills.py")
    sk = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(sk)
    found: dict[str, dict] = {}
    files = sorted((ROOT / "docs").glob("*.md")) + sorted((ROOT / "integrations" / "skills-src").rglob("*.md"))
    for f in files:
        text = f.read_text()
        for m in re.finditer(r"(?<![A-Za-z0-9_./-])([a-z][a-z0-9_]*)\s*\{", text):
            name = m.group(1)
            if name not in tools:
                continue
            end = sk.balanced(text, m.end() - 1)
            if end < 0:
                continue
            raw = text[m.end() - 1:end]
            if len(raw) > 400:
                continue
            try:
                args = json.loads(sk.js_to_json(sk.strip_comments(raw)))
            except json.JSONDecodeError:
                continue
            if not isinstance(args, dict) or not args:
                continue
            problems: list[str] = []
            sk.check_call(name, args, tools, "", problems)
            if problems or len(json.dumps(args)) > 360:
                continue
            best = found.get(name)
            if best is None or len(args) > len(best):
                found[name] = args
    _MINED = found
    return found


def example_args(tool: dict, tools: dict[str, dict] | None = None):
    found = described_example(tool["description"])
    if found is not None:
        return found, True
    curated = CURATED.get(tool["name"])
    if curated is not None:
        return curated.get("_args", curated), True
    if tools is not None:
        mined = mined_examples(tools).get(tool["name"])
        if mined is not None:
            return mined, True
    schema = tool["inputSchema"]
    props = schema.get("properties", {})
    return {k: sample_value(k, props.get(k, {})) for k in schema.get("required", [])}, False


def type_text(schema: dict) -> str:
    if not isinstance(schema, dict):
        return ""
    t = schema.get("type")
    if t is None:
        if "oneOf" in schema or "anyOf" in schema:
            return " \\| ".join(type_text(s) for s in schema.get("oneOf", schema.get("anyOf", [])))
        desc = schema.get("description", "")
        if "hex string" in desc or "#rrggbb" in desc:
            return "color"
        return "any"
    if isinstance(t, list):
        return " \\| ".join(t)
    if t == "array":
        items = schema.get("items")
        inner = type_text(items) if isinstance(items, dict) else ""
        n = schema.get("minItems")
        if n and n == schema.get("maxItems"):
            return f"{inner or 'any'}[{n}]"
        return f"{inner}[]" if inner else "array"
    return t


def constraints(schema: dict) -> str:
    parts = []
    if "enum" in schema:
        parts.append(" ".join(f"`{e}`" for e in schema["enum"]))
    lo, hi = schema.get("minimum"), schema.get("maximum")
    if lo is not None and hi is not None:
        parts.append(f"{fmt_num(lo)} .. {fmt_num(hi)}")
    elif lo is not None:
        parts.append(f"≥ {fmt_num(lo)}")
    elif hi is not None:
        parts.append(f"≤ {fmt_num(hi)}")
    if "default" in schema:
        parts.append(f"default `{json.dumps(schema['default'])}`")
    return "<br>".join(parts)


def fmt_num(v) -> str:
    return str(int(v)) if isinstance(v, float) and v.is_integer() else str(v)


def compact(value) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(", ", ": "))


