def component_section(name: str, schema: dict) -> str:
    lines = [f"## `{name}` {{ #{name} }}", "", schema.get("description", "").strip(), ""]
    props = schema.get("properties", {})
    if props:
        lines += ["| Field | Type | Description | Values |", "|---|---|---|---|"]
        for field, sub in props.items():
            lines.append(f"| `{field}` | {type_text(sub)} | {md_escape(sub.get('description', ''))} | {constraints(sub)} |")
        lines.append("")
    first = next(iter(props), None)
    if name == "environment":
        lines += ['=== "Tool call"', "", "    ```tool", f"    environment_update {compact({'preset': 'sunset'})}", "    ```",
                  "", '=== "Wander"', "", "    Environment fields are scene settings, edited with `environment_update` "
                  "(or keyed in sequences as `environment.<field>`).", ""]
    elif first:
        lines += ['=== "Tool call"', "", "    ```tool",
                  f"    entity_update {compact({'entity': 'Crate', 'components': {name: {}}})}", "    ```", "",
                  f'=== "Wander"', "", "    ```text", f"    self.{name}.{first}          -- read or write any field", "    ```", ""]
    return "\n".join(lines)


def gen_components(comps: dict) -> dict[str, str]:
    pages = {}
    placed = {c for _, _, members in COMPONENT_GROUPS.values() for c in members}
    missing = [c for c in comps if c not in placed]
    if missing:
        raise SystemExit(f"components without a reference page: {', '.join(missing)}: add them to COMPONENT_GROUPS in "
                         "website/scripts/gen_reference.py")
    idx = [BANNER, "# Components", "",
           f"Every component is a plain struct with a reflected field table. The same table drives JSON scene files, "
           f"the JSON Schema agents read (`component_schema`), the editor's property grid and Wander access "
           f"(`self.light.intensity`). There are **{len(comps) - (1 if 'environment' in comps else 0)} components** "
           "plus the scene-wide environment.", "",
           "Set them with `entity_create` / `entity_update` (component objects are merged field by field), from the "
           "editor's Details panel, or from Wander. Unknown fields fail with a *did you mean …?* hint.", "",
           "| Component | Group | Description |", "|---|---|---|"]
    for key, (title, intro, members) in COMPONENT_GROUPS.items():
        for c in members:
            if c in comps:
                idx.append(f"| [`{c}`]({key}.md#{c}) | {title} | {md_escape(comps[c].get('description', ''))} |")
    pages["reference/components/index.md"] = "\n".join(idx) + "\n"
    for key, (title, intro, members) in COMPONENT_GROUPS.items():
        body = [BANNER, f"# {title}", "", intro, ""]
        for c in members:
            if c in comps:
                body.append(component_section(c, comps[c]))
        pages[f"reference/components/{key}.md"] = "\n".join(body)
    return pages


