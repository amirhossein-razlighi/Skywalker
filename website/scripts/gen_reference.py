def gen_cli(cli: dict) -> dict[str, str]:
    usage = cli["usage"].rstrip()
    out = [BANNER, "# Command line", "",
           "`skywalker` is the headless engine: MCP server, renderer, simulator, Wander compiler, tool runner, studio "
           "runner, packager and movie renderer in one binary (`build/<preset>/bin/skywalker`). The help texts below are "
           "captured from the binary itself.", "",
           "| Command | Purpose |", "|---|---|"]
    out += [f"| [`skywalker {c}`](#{c}) | {d} |" for c, d in CLI_NOTES.items()]
    out += ["", "## Usage", "", "```text", *usage.splitlines(), "```", ""]
    for c, d in CLI_NOTES.items():
        out += [f"## `skywalker {c}` {{ #{c} }}", "", d, ""]
        if c in cli["commands"]:
            out += ["```text", *cli["commands"][c].rstrip().splitlines(), "```", ""]
        else:
            lines = [l for l in usage.splitlines() if re.match(rf"\s*skywalker {c}\b", l)]
            if lines:
                out += ["```text", *lines, "```", ""]
    return {"reference/cli.md": "\n".join(out)}


def gen_capi(capi: dict) -> dict[str, str]:
    out = [BANNER, "# C API", "",
           "The engine's stable ABI is a small C header, "
           f"[`engine/capi/include/sky_api.h`]({REPO}engine/capi/include/sky_api.h). The SwiftUI editor is built on it, and "
           "any language with a C FFI (Swift, Python, Rust, C#, Zig, JavaScript) can embed the engine with it.", "",
           '!!! info "Design"', ""]
    out += ["    " + l if l else "" for l in capi["intro"].splitlines()]
    out.append("")
    for sec in capi["sections"]:
        out += [f"## {sec['title']}", "", "| Declaration | Notes |", "|---|---|"]
        for item in sec["items"]:
            if item["kind"] == "struct":
                continue
            out.append(f"| `{md_escape(item['decl'])}` | {md_escape(item['doc'])} |")
        out.append("")
        for item in sec["items"]:
            if item["kind"] == "struct":
                out += [md_escape(item["doc"]), "", "```c", *item["decl"].splitlines(), "```", ""]
    out += ["## Example", "", "```c",
            '#include "sky_api.h"',
            "",
            "int main(void) {",
            '    SkyEngine* engine = sky_engine_create("my_game");',
            '    char* result = sky_call_tool(engine, "entity_create",',
            '                                 "{\\"name\\": \\"Crate\\", \\"mesh\\": \\"cube\\", \\"position\\": [0, 0.5, 0]}",',
            '                                 "user");',
            "    sky_string_free(result);",
            "    sky_update(engine, 1.0 / 60.0);",
            "    sky_engine_destroy(engine);",
            "    return 0;",
            "}", "```", ""]
    return {"reference/capi.md": "\n".join(out)}


