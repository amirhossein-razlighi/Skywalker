def tools_by_category(tools: list[dict]):
    cats: dict[str, list[dict]] = OrderedDict((c, []) for c in CATEGORIES)
    for t in tools:
        cat = t.get("_meta", {}).get("skywalker/category", "misc")
        if cat not in cats:
            raise SystemExit(f"tool category '{cat}' ({t['name']}) has no page: add it to CATEGORIES in "
                             "website/scripts/gen_reference.py and to the Reference > Tools nav in website/mkdocs.yml")
        cats[cat].append(t)
    return cats


def badges(tool: dict) -> str:
    ann = tool.get("annotations", {})
    out = []
    if ann.get("readOnlyHint"):
        out.append('<span class="sky-badge sky-badge--ro" title="Never changes the scene">read-only</span>')
    else:
        out.append('<span class="sky-badge sky-badge--mut" title="Changes the project; undoable and attributed">mutating</span>')
    if ann.get("destructiveHint"):
        out.append('<span class="sky-badge" title="May remove or overwrite data">destructive</span>')
    if ann.get("openWorldHint"):
        out.append('<span class="sky-badge sky-badge--open" title="Reaches outside the engine (network or other programs); '
                   'clients ask the human first">open-world</span>')
    return " ".join(out)


def param_rows(schema: dict, prefix: str = "", depth: int = 0) -> list[str]:
    rows = []
    required = set(schema.get("required", []))
    for name, sub in schema.get("properties", {}).items():
        if not isinstance(sub, dict):
            continue
        req = "yes" if name in required else ""
        desc = md_escape(sub.get("description", ""))
        rows.append(f"| `{prefix}{name}` | {type_text(sub)} | {req} | {desc} | {constraints(sub)} |")
        if depth < 1 and sub.get("type") == "object" and sub.get("properties"):
            rows += param_rows(sub, f"{prefix}{name}.", depth + 1)
        items = sub.get("items")
        if depth < 1 and isinstance(items, dict) and items.get("properties"):
            rows += param_rows(items, f"{prefix}{name}[].", depth + 1)
    return rows


def tool_section(tool: dict) -> str:
    name = tool["name"]
    title = tool.get("title") or name
    lines = [f"### `{name}` {{ #{name} }}", "", f"**{md_escape(title)}** {badges(tool)}", "", tool["description"].strip(), ""]
    rows = param_rows(tool["inputSchema"])
    if rows:
        lines += ["| Argument | Type | Required | Description | Values |", "|---|---|---|---|---|", *rows, ""]
    else:
        lines += ["Takes no arguments.", ""]
    args, from_desc = example_args(tool, TOOLS_BY_NAME)
    call = compact(args)
    shell = call.replace("'", "'\\''")
    rpc = {"jsonrpc": "2.0", "id": 1, "method": "tools/call", "params": {"name": name, "arguments": args}}
    lines += [
        '=== "Tool call"', "", "    ```tool", f"    {name} {call}", "    ```", "",
        '=== "CLI"', "", "    ```bash", f"    skywalker call {name} '{shell}' --project my_game", "    ```", "",
        '=== "MCP request"', "", "    ```json", *("    " + l for l in json.dumps(rpc, indent=2, ensure_ascii=False).splitlines()),
        "    ```", "",
    ]
    if not from_desc and args:
        lines += ["<small>Minimal call with the required arguments; see the table for everything else.</small>", ""]
    note = CURATED.get(tool["name"], {}).get("_note")
    if note:
        lines += [f"<small>{note}</small>", ""]
    return "\n".join(lines)


