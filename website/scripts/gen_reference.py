def generate() -> dict[str, str]:
    CURATED.clear()
    CURATED.update({k: v for k, v in load("tool_examples.json").items() if not k.startswith("_")})
    pages = {}
    pages.update(gen_tools(load("tools.json")))
    pages.update(gen_components(load("components.json")))
    pages.update(gen_wander(load("wander.json")))
    pages.update(gen_cli(load("cli.json")))
    pages.update(gen_capi(load("capi.json")))
    pages.update(gen_examples(load("examples.json")))
    out = {}
    for rel, text in pages.items():
        # Front matter gives the page its title (the banner comment would otherwise hide the first heading).
        m = re.match(re.escape(BANNER) + r"\n?# (.+)\n", text)
        if m:
            title = m.group(1).replace('"', "'")
            text = f'---\ntitle: "{title}"\n---\n' + text
        out[rel] = text.rstrip() + "\n"
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if committed pages differ from what would be generated")
    ap.add_argument("--fresh", help="folder with a fresh dump_data.py output to compare website/data against")
    opts = ap.parse_args()
    problems = []
    if opts.fresh:
        for name in ("tools.json", "components.json", "wander.json", "cli.json", "capi.json"):
            fresh, committed = Path(opts.fresh) / name, DATA / name
            if not committed.exists() or fresh.read_text() != committed.read_text():
                problems.append(f"website/data/{name} is stale (the engine changed)")
    pages = generate()
    if opts.check:
        for rel, text in pages.items():
            path = DOCS / rel
            if not path.exists() or path.read_text() != text:
                problems.append(f"website/docs/{rel} is stale")
        generated = {DOCS / rel for rel in pages}
        for path in list((DOCS / "reference").rglob("*.md")):
            if BANNER in path.read_text()[:400] and path not in generated:
                problems.append(f"website/docs/{path.relative_to(DOCS)} is no longer generated: delete it")
        for p in problems:
            print(p)
        if problems:
            print("regenerate: python3 website/scripts/dump_data.py --cli build/<preset>/bin/skywalker && "
                  "python3 website/scripts/gen_reference.py", file=sys.stderr)
            return 1
        print(f"reference pages up to date ({len(pages)} pages)")
        return 0
    for p in problems:
        print(p)
    for rel, text in pages.items():
        path = DOCS / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
    print(f"wrote {len(pages)} pages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
