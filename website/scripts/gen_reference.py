def gen_wander(w: dict) -> dict[str, str]:
    guide = w["guide"]
    w = {"guide": guide, "categories": OrderedDict(
        (c, [e for e in es if "name" in e]) for c, es in w["categories"].items() if any("name" in e for e in es))}
    triggers = []
    m = re.search(r"SUBSYSTEM TRIGGERS\n(.*?)(?:\nMore:|\Z)", guide, re.S)
    if m:
        for line in m.group(1).splitlines():
            tm = re.match(r"\s*(on \w+) — (.*)", line)
            if tm:
                triggers.append((tm.group(1), tm.group(2)))
    count = sum(len(v) for v in w["categories"].values())
    out = [BANNER, "# Wander builtins", "",
           f"Every function a Wander script can call lives in one registry: name, typed parameters, return type, category, "
           f"documentation and an example. The compiler checks calls against it (arity, types, did-you-mean), and this page "
           f"is generated from it. **{count} builtins** in {len(w['categories'])} categories.", "",
           "Agents get the same information from `wander_reference` (the guide) and `wander_reference {topic}` "
           "(structured entries for a category or a function). For the language itself, read the "
           "[Wander manual](../manual/wander/index.md).", "",
           "| Category | Builtins |", "|---|---|"]
    for cat, entries in w["categories"].items():
        names = ", ".join(f"[`{e['name']}`](#{slug(cat)}-{slug(e['name'])})" for e in entries)
        out.append(f"| [{cat}](#{slug(cat)}) | {names} |")
    out.append("")
    if triggers:
        out += ["## Subsystem triggers", "", "Besides the core triggers (`on start`, `on tick`, `on event`, `on key`, "
                "`on click`, `on frame`, and `on enter` / `on exit` inside states), subsystems register these:", "",
                "| Trigger | Fires when |", "|---|---|"]
        out += [f"| `{t}` | {md_escape(d)} |" for t, d in triggers]
        out.append("")
    for cat, entries in w["categories"].items():
        out += [f"## {cat} {{ #{slug(cat)} }}", ""]
        for e in entries:
            out += [f"### `{e['name']}` {{ #{slug(cat)}-{slug(e['name'])} }}", "", "```text", e["signature"], "```", "",
                    e.get("doc", "").strip(), ""]
            params = e.get("params", [])
            if params:
                out += ["| Parameter | Type | |", "|---|---|---|"]
                for p in params:
                    out.append(f"| `{p['name']}` | {md_escape(p.get('type', 'any'))} | {'optional' if p.get('optional') else ''} |")
                out.append("")
            if e.get("returns"):
                out += [f"Returns: `{e['returns']}`", ""]
            if e.get("example"):
                out += ["```text", e["example"], "```", ""]
    out += ["## The guide agents read", "",
            "`wander_reference` without a topic returns this text: a compact language guide followed by the builtin list.",
            "", '??? note "wander_reference output"', "", "    ```text"]
    out += ["    " + l if l else "" for l in guide.rstrip().splitlines()]
    out += ["    ```", ""]
    return {"reference/wander.md": "\n".join(out)}


