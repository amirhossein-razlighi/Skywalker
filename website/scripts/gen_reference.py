def scene_stats(project: Path) -> dict:
    kinds: Counter = Counter()
    entities = behaviors = 0
    env = {}
    scenes = []
    for f in sorted((project / "scenes").glob("*.sky.json")):
        if " 2." in f.name:  # iCloud duplicates
            continue
        scenes.append(f.relative_to(project).as_posix())
        try:
            doc = json.loads(f.read_text())
        except (OSError, json.JSONDecodeError):
            continue
        env = env or doc.get("environment", {})
        for e in doc.get("entities", []):
            entities += 1
            behaviors += len(e.get("behaviors", []))
            kinds.update(e.get("components", {}).keys())
    return {"scenes": scenes, "kinds": kinds, "entities": entities, "behaviors": behaviors, "env": env}


FEATURE_FROM_COMPONENT = OrderedDict([
    ("terrain", "Terrain"), ("foliage", "Foliage"), ("water", "FFT water"), ("fluid", "Fluid fire and smoke"),
    ("particles", "Particles"), ("groom", "Hair"), ("sprite", "Sprites"), ("tilemap", "Tilemaps"), ("light2d", "2D lights"),
    ("ui", "UI"), ("text", "World text"), ("dialogue", "Dialogue"), ("body", "Physics"), ("character", "Characters"),
    ("nav_agent", "Navigation"), ("animator", "Skeletal animation"), ("sequencer", "Sequences"), ("audio", "Audio"),
])


def gen_examples(curated: dict) -> dict[str, str]:
    projects = sorted(p for p in (ROOT / "examples").iterdir() if p.is_dir() and (p / "scenes").is_dir())
    unknown = [p.name for p in projects if p.name not in curated["projects"]]
    if unknown:
        raise SystemExit(f"examples without an entry in website/data/examples.json: {', '.join(unknown)}")
    order = list(curated["projects"])
    projects.sort(key=lambda p: order.index(p.name))
    cards, sections = [], []
    for p in projects:
        info = curated["projects"][p.name]
        game = {}
        if (p / "game.json").exists():
            game = json.loads((p / "game.json").read_text())
        title = game.get("title", info.get("title", p.name))
        genre = game.get("genre", info.get("genre", ""))
        pitch = game.get("pitch", info.get("pitch", ""))
        stats = scene_stats(p)
        auto = [label for comp, label in FEATURE_FROM_COMPONENT.items() if stats["kinds"].get(comp)]
        if stats["behaviors"]:
            auto.append("Wander")
        sky = stats["env"].get("skyMode")
        if sky in ("atmosphere", "hdri"):
            auto.append("HDRI sky" if sky == "hdri" else "Atmosphere")
        if stats["env"].get("cloudMode") == "volumetric" and stats["env"].get("clouds", 0) > 0:
            auto.append("Volumetric clouds")
        features = list(dict.fromkeys(info.get("features", []) + auto))
        image = info.get("image")
        media = (f'<img src="../assets/{image}" alt="{title}" loading="lazy">' if image else
                 '<div class="sky-placeholder"><strong>Render on first build</strong>'
                 'This project downloads its CC0 assets on first build</div>')
        tags = "".join(f'<span class="sky-tag">{f}</span>' for f in features[:6])
        cards.append(f'<a class="sky-card" href="#{p.name}">{media}<div class="sky-card__body">'
                     f'<p class="sky-card__title">{title}</p><p class="sky-card__meta">{genre}</p>'
                     f'<p class="sky-card__text">{pitch}</p><div class="sky-tags">{tags}</div></div></a>')
        sec = [f"## {title} {{ #{p.name} }}", ""]
        if info.get("video"):
            poster = f' poster="../assets/{image}"' if image else ""
            sec += [f'<video controls muted loop playsinline preload="none"{poster}>'
                    f'<source src="../assets/{info["video"]}" type="video/mp4"></video>', ""]
        elif image:
            sec += [f"![{title}](../assets/{image}){{ loading=lazy }}", ""]
        sec += [f"*{genre}* · {pitch}" if genre else pitch, "", info["description"].strip(), ""]
        sec += ["| | |", "|---|---|",
                f"| Folder | [`examples/{p.name}`]({REPO}examples/{p.name}) |",
                f"| Scenes | {', '.join(f'`{s}`' for s in stats['scenes'])} |",
                f"| Size | {stats['entities']} entities, {stats['behaviors']} behaviors |",
                f"| Demonstrates | {', '.join(features)} |"]
        if game.get("assets"):
            sec.append(f"| Assets | {md_escape(game['assets'])} |")
        if info.get("needs_download"):
            sec.append("| Note | Downloads its CC0 assets (models, textures, HDRI) on the first build; see the project's "
                       "`CREDITS.md` |")
        sec.append("")
        scene = stats["scenes"][0] if stats["scenes"] else "scenes/main.sky.json"
        sec += ['=== "Editor"', "", "    ```bash",
                f'    open build/release/bin/Skywalker.app --args --project "$PWD/examples/{p.name}"', "    ```", "",
                '=== "Render a still"', "", "    ```bash",
                f"    skywalker render examples/{p.name}/{scene} -o {p.name}.png --scene-camera --samples 8", "    ```", "",
                '=== "Play it"', "", "    ```bash", f"    skywalker-player examples/{p.name}", "    ```", "",
                '=== "Agent"', "", "    ```bash", f"    skywalker mcp --project examples/{p.name} --scene {scene}", "    ```", ""]
        sections.append("\n".join(sec))
    page = [BANNER, "# Examples", "",
            f"{len(projects)} sample projects ship in [`examples/`]({REPO}examples). Most were built by agent crews "
            "through the engine's own tools, and every one is original: its own world, characters and story. Open any of "
            "them in the editor, render it from the command line, play it in the standalone player, or point an agent at it.",
            "", '<div class="sky-grid">', *cards, "</div>", "", *sections]
    return {"examples/index.md": "\n".join(page)}


